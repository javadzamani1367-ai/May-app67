    /** پهنای لازم برای یک متن در یک سبک، به واحد پهنای اکسل. */
    public static function fit(string $text, int $style): float
    {
        $size = self::SIZE[$style] ?? 9;
        $longest = 0;
        foreach (explode("\n", $text) as $line) {
            $longest = max($longest, mb_strlen($line));
        }
        return $longest * 0.42 * $size / 5.25 + 1.2;
    }

